// planes_tarifarios.fecha se guarda en UTC sin zona: 04/11/2026 00:00 en México = 06:00 UTC.
export const INICIO_TABULADOR_NOV2026 = "2026-11-04T06:00:00";

const usaTabuladorNuevo = (fecha: string | null | undefined): boolean => {
  if (!fecha) return true;
  const f = fecha.trim().replace(" ", "T").slice(0, 19);
  return f >= INICIO_TABULADOR_NOV2026;
};

/**
 * Calcula la comision de un plan tarifario.
 * @param categoria  ej. 'LÍNEA NUEVA'
 * @param clasificacion ej. 'TELCEL LIBRE CONTROLADO 4'
 * @param tipoPlan 'FORZOSO' (con equipo) o 'LIBRE' (solo linea)
 * @param fecha fecha del plan (planes_tarifarios.fecha); define qué tabulador aplica
 * @returns monto de comision en pesos, o null si no se encuentra
 */
export function calcularComision(
  categoria: string | null | undefined,
  clasificacion: string | null | undefined,
  tipoPlan: string | null | undefined,
  fecha?: string | null
): number | null {
  if (!categoria || !clasificacion) return null;
  let cat = categoria.trim().toUpperCase();
  let clas = clasificacion.trim().toUpperCase();
  // En planes_tarifarios el módem se guarda como MODEM / "INTERNET EN TU CASA LIBRE 3"
  if (cat === 'MODEM' && clas.startsWith('INTERNET EN TU CASA ')) {
    cat = 'MODEM INTERNET EN TU CASA';
    clas = clas.replace('INTERNET EN TU CASA ', '');
  }
  const key = `${cat}||${clas}`;
  const tabla = usaTabuladorNuevo(fecha) ? TABULADOR_COMISIONES_NOV2026 : TABULADOR_COMISIONES;
  const montos = tabla[key];
  if (!montos) return null;
  const esForzoso = (tipoPlan ?? '').trim().toUpperCase() === 'FORZOSO';
  return esForzoso ? montos.forzoso : montos.libre;
}
