/**
 * Calcula la comision de un plan tarifario.
 * @param categoria  ej. 'LÍNEA NUEVA'
 * @param clasificacion ej. 'TELCEL LIBRE CONTROLADO 4'
 * @param tipoPlan 'FORZOSO' (con equipo) o 'LIBRE' (solo linea)
 * @returns monto de comision en pesos, o null si no se encuentra
 */
export function calcularComision(
  categoria: string | null | undefined,
  clasificacion: string | null | undefined,
  tipoPlan: string | null | undefined
): number | null {
  if (!categoria || !clasificacion) return null;
  const key = `${categoria.trim()}||${clasificacion.trim()}`;
  const montos = TABULADOR_COMISIONES[key];
  if (!montos) return null;
  const esForzoso = (tipoPlan ?? '').trim().toUpperCase() === 'FORZOSO';
  return esForzoso ? montos.forzoso : montos.libre;
}
